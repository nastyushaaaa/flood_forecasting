"""Фазы водного режима Амура у Хабаровска (задача 2.5).

Границы заданы по месяцам, по средним уровням 2002–2026 гг.:
половодье — апрель–май (таяние снега, ледоход), паводок — июнь–сентябрь (дождевые паводки, пик в августе),
межень — октябрь–март (спад и низкая зимняя вода).
"""
import pandas as pd

PHASE_BY_MONTH = {
    1: 'межень', 2: 'межень', 3: 'межень',
    4: 'половодье', 5: 'половодье',
    6: 'паводок', 7: 'паводок', 8: 'паводок', 9: 'паводок',
    10: 'межень', 11: 'межень', 12: 'межень',
}


def phase_of(dates: pd.Series) -> pd.Series:
    """Фаза водного режима для каждой даты: 'половодье', 'паводок' или 'межень'."""
    return pd.to_datetime(dates).dt.month.map(PHASE_BY_MONTH)
